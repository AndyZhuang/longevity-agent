for (const locale of LOCALES) {
  const file = resolve(LOCALE_DIR, `${locale}.json`);
  const data = JSON.parse(readFileSync(file, "utf-8"));
  const content = CONTENT[locale];

  // Idempotency: skip if already merged
  if (data.terms && data.privacy && data.conduct && data.faq) {
    console.log(`[${locale}] already has terms/privacy/conduct/faq — skipping`);
    continue;
  }

  // Merge: nav keys (only those that don't exist), footer keys, seo keys, legal,
  // terms, privacy, conduct, faq
  for (const [topKey, topVal] of Object.entries(content)) {
    if (topKey === "nav" || topKey === "footer" || topKey === "seo") {
      // Merge into existing — only fill in missing keys (don't clobber existing)
      data[topKey] = { ...(data[topKey] ?? {}), ...topVal };
    } else {
      // Top-level new namespace — just set
      data[topKey] = topVal;
    }
  }

  // Ensure the new SEO keys live under seo.* as nested objects (not flat strings)
  if (data.seo && !data.seo.terms) {
    // already handled above via the spread
  }

  writeFileSync(file, JSON.stringify(data, null, 2) + "\n", "utf-8");
  console.log(`[${locale}] ✓ wrote ${Object.keys(content).join(", ")}`);
}

